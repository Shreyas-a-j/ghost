use serde_json::json;
use std::{fs, process::Command};
use tempfile::tempdir;

const EXPECTED_STATE: &str = r#"# State
<!-- ghost:focus -->
## Current focus
- Project initialized. Read `specs/00-overview.md` and run `/plan`.
<!-- ghost:next -->
## Next steps
- [ ] `/plan`
- [ ] `/build task-board`
<!-- ghost:done -->
## Done
- Nothing yet.
<!-- ghost:decisions -->
## Decisions
- Project generated by ghost; no application decisions yet.
<!-- ghost:blockers -->
## Blockers
- None.

Keep these limits while editing: Current focus 1-3 lines; Next up to 5 checkboxes; Done the last 10 items; Decisions 10 one-line entries with reasons.
"#;

#[test]
fn existing_projects_keep_source_and_generate_repeatable_handoffs() {
    for (stack, manifest, source) in [
        ("rust", "Cargo.toml", "[workspace]\nmembers = []\n"),
        ("python", "pyproject.toml", "[tool.pytest.ini_options]\n"),
        ("typescript_node", "package.json", "{\"private\":true}\n"),
    ] {
        let workspace = tempdir().unwrap();
        let project = workspace.path().join("existing project");
        fs::create_dir(&project).unwrap();
        fs::write(project.join(manifest), source).unwrap();
        fs::write(project.join(".gitignore"), "local-cache/\n").unwrap();
        let answers = json!({
            "project_name": "Orbit", "pitch": "Track tasks",
            "demo_steps": ["Open", "Create", "View"], "event_name": "",
            "deadline": "2099-01-01 12:00", "team_size": "solo", "mode": "normal",
            "stack": stack, "stack_details": "", "run_cmd": "",
            "must_haves": ["Task board"], "nice_to_haves": [], "existing_code": true,
            "risky_areas": [], "test_level": "smoke", "model_override": null,
            "skills": [], "checkpoint_freq": "manual", "created_at": "2026-01-01T00:00:00Z"
        });
        let input = workspace.path().join("answers.json");
        fs::write(&input, answers.to_string()).unwrap();
        let run = |args: &[&str]| {
            Command::new(env!("CARGO_BIN_EXE_ghost"))
                .args(args)
                .current_dir(&project)
                .env("GHOST_OPENCODE_DIR", workspace.path().join("opencode"))
                .env("GHOST_AGENTS_DIR", workspace.path().join("agents"))
                .output()
                .unwrap()
        };
        let init = ["new", "--answers", input.to_str().unwrap()];
        for args in [init.as_slice(), &["regen"]] {
            let result = run(args);
            assert!(
                result.status.success(),
                "{stack}: {}",
                String::from_utf8_lossy(&result.stderr)
            );
            assert_eq!(fs::read_to_string(project.join(manifest)).unwrap(), source);
            assert_eq!(
                fs::read_to_string(project.join("STATE.md")).unwrap(),
                EXPECTED_STATE
            );
            let ignore = fs::read_to_string(project.join(".gitignore")).unwrap();
            for entry in [
                "local-cache/",
                ".env",
                ".env.*",
                ".ghost/dev.pid",
                ".ghost/dev.log",
            ] {
                assert_eq!(ignore.lines().filter(|line| *line == entry).count(), 1);
            }
        }
        fs::write(project.join("STATE.md"), "Developer handoff\n").unwrap();
        let conflict = run(&init);
        assert!(!conflict.status.success());
        assert!(String::from_utf8_lossy(&conflict.stderr).contains("STATE.md"));
        assert_eq!(
            fs::read_to_string(project.join("STATE.md")).unwrap(),
            "Developer handoff\n"
        );
    }
}
